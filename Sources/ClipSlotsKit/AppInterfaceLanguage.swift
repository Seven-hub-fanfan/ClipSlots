import Foundation

/// Interface preferences are independent of the system language and stored content.
public enum AppInterfaceLanguage: String, CaseIterable, Identifiable, Hashable {
    case chinese = "zh-Hans"
    case english = "en"

    public static let preferenceKey = "interfaceLanguage"
    public var id: String { rawValue }
    public var nativeTitle: String { self == .chinese ? "中文" : "English" }
    public var locale: Locale { Locale(identifier: rawValue) }
    public static func resolve(_ value: String?) -> Self {
        Self(rawValue: value ?? "") ?? .chinese
    }
    public static func current(defaults: UserDefaults = .standard) -> Self {
        resolve(defaults.string(forKey: preferenceKey))
    }
}

